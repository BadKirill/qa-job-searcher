CREATE TABLE tasks (
	id VARCHAR(128) NOT NULL,
	user_id VARCHAR(128) NOT NULL,
	kind TEXT NOT NULL,
	scope TEXT NOT NULL,
	request_id TEXT NOT NULL,
	payload JSONB DEFAULT '{}'::jsonb NOT NULL,
	result JSONB DEFAULT '{}'::jsonb NOT NULL,
	status TEXT DEFAULT 'queued' NOT NULL,
	error TEXT,
	job_id VARCHAR(128),
	template_id VARCHAR(128),
	conversation_id VARCHAR(128),
	lease_until FLOAT,
	worker_id TEXT,
	attempts INTEGER DEFAULT '0' NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	CONSTRAINT pk_tasks PRIMARY KEY (id),
	CONSTRAINT uq_tasks_user_id_request_id UNIQUE (user_id, request_id),
	CONSTRAINT fk_tasks_user_id_job_id_job_matches FOREIGN KEY(user_id, job_id) REFERENCES job_matches (user_id, job_id),
	CONSTRAINT fk_tasks_user_id_template_id_candidate_templates FOREIGN KEY(user_id, template_id) REFERENCES candidate_templates (user_id, id),
	CONSTRAINT fk_tasks_user_id_conversation_id_conversations FOREIGN KEY(user_id, conversation_id) REFERENCES conversations (user_id, id),
	CONSTRAINT task_kind CHECK (kind IN ('search','chat','cv','cover_letter')),
	CONSTRAINT task_status CHECK (status IN ('queued','running','verifying','rendering','ready','failed','needs_input','blocked','cancelled','deleted')),
	CONSTRAINT task_attempts CHECK (attempts >= 0),
	CONSTRAINT task_template_payload CHECK (template_id IS NOT DISTINCT FROM (payload #>> '{context,template,id}')),
	CONSTRAINT task_job_payload CHECK (job_id IS NOT DISTINCT FROM COALESCE(payload ->> 'job_id', payload #>> '{context,job,id}')),
	CONSTRAINT task_conversation_payload CHECK (conversation_id IS NOT DISTINCT FROM (payload ->> 'conversation_id')),
	CONSTRAINT task_context_owner CHECK (NOT (payload ? 'context') OR (payload #>> '{context,owner_id}') IS NOT DISTINCT FROM user_id),
	CONSTRAINT uq_tasks_user_id_id UNIQUE (user_id, id),
	CONSTRAINT fk_tasks_user_id_users FOREIGN KEY(user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX one_active_task_scope ON tasks (user_id, scope) WHERE status IN ('queued', 'running', 'verifying', 'rendering');

CREATE INDEX tasks_pending ON tasks (status, created_at);

