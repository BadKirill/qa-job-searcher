CREATE TABLE auth_attempts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	key_hash TEXT NOT NULL,
	ip_hash TEXT NOT NULL,
	created_at FLOAT NOT NULL,
	CONSTRAINT pk_auth_attempts PRIMARY KEY (id)
);
CREATE INDEX auth_attempts_ip_time ON auth_attempts (ip_hash, created_at);
CREATE INDEX auth_attempts_key_time ON auth_attempts (key_hash, created_at);
ALTER TABLE invitations ADD COLUMN created_by_id VARCHAR(128) CONSTRAINT fk_invitations_created_by_id_users REFERENCES users(id);
ALTER TABLE password_reset_tokens ADD COLUMN created_by_id VARCHAR(128) CONSTRAINT fk_password_reset_tokens_created_by_id_users REFERENCES users(id);
